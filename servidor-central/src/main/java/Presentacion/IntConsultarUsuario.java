    private void comboUsuarioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_comboUsuarioActionPerformed
        // TODO add your handling code here:
        String nickname = (String) comboUsuario.getSelectedItem();

        if (nickname == null) {
        return;
    }
        Usuario usuario = controladorUsuario.buscarUsuario(nickname);

        cargarDatosUsuario(usuario);

        if (usuario instanceof Docente) {
            cargarDatosDocente((Docente) usuario);
        } else if (usuario instanceof Estudiante) {
            cargarDatosEstudiante((Estudiante) usuario);
        }
        
        if (usuario != null) {
        cargarDatosUsuario(usuario);
        cargarImagenUsuario(usuario.getNickname());
}
        
    }//GEN-LAST:event_comboUsuarioActionPerformed
    
    private void cargarDatosUsuario(Usuario usuario) {
        lbValorNick.setText(usuario.getNickname());
        lbValorName.setText(usuario.getNombre());
        lbValorApellido.setText(usuario.getApellido());
        lbValorMail.setText(usuario.getCorreoElectronico());
        lbValorFechaNacimiento.setText(usuario.getFecNac().format(DateTimeFormatter.ofPattern("dd/MM/yyyy")));
        lbValorTipo.setText(usuario.getClass().getSimpleName());

        lbValorNick.setEditable(false);
        lbValorName.setEditable(false);
        lbValorApellido.setEditable(false);
        lbValorMail.setEditable(false);
        lbValorFechaNacimiento.setEditable(false);
        lbValorTipo.setEditable(false);
    }
    
    private void cargarImagenUsuario(String nickname) {

    File carpetaImagenes = new File("imagenesUsuarios");

    File imagen = new File(carpetaImagenes, nickname + ".jpg");

    if (!imagen.exists()) {
        imagen = new File(carpetaImagenes, nickname + ".jpeg");
    }

    if (!imagen.exists()) {
        imagen = new File(carpetaImagenes, nickname + ".png");
    }

    if (imagen.exists()) {

        ImageIcon icono = new ImageIcon(imagen.getAbsolutePath());

        Image imagenEscalada = icono.getImage().getScaledInstance(
                lbImagen.getWidth(),
                lbImagen.getHeight(),
                Image.SCALE_SMOOTH
        );

        lbImagen.setIcon(new ImageIcon(imagenEscalada));
        lbImagen.setText("");

    } else {

        lbImagen.setIcon(null);
        lbImagen.setText("Sin imagen");
    }
}
    
    private void cargarDatosDocente(Docente docente) {
        panelInfo.setVisible(true);
        cardLayout.show(panelInfo, "docente");

        cargarCursosDocente(docente);
        cargarEdicionesDocente(docente);
        cargarProgramasDocente(docente);
    }
    
    private void cargarCursosDocente(Docente docente) {
        DefaultListModel<String> modeloCursos = new DefaultListModel<>();

        for (Curso curso : docente.getCursos()) {
            modeloCursos.addElement(curso.getNombre());
        }

        jList1.setModel(modeloCursos);
    }
    
    private void cargarEdicionesDocente(Docente docente) {
        DefaultListModel<String> modeloEdiciones = new DefaultListModel<>();

        for (EdicionCurso edicion : docente.getEdiciones()) {
            modeloEdiciones.addElement(edicion.toString());
        }

        jList2.setModel(modeloEdiciones);
    }
    
    private void cargarProgramasDocente(Docente docente) {
        DefaultListModel<String> modeloProgramas = new DefaultListModel<>();

        for (ProgramaFormacion programa : controladorPrograma.listarProgramas().values()) {

            for (Curso curso : docente.getCursos()) {

                if (programa.getCursos().contains(curso)) {
                    modeloProgramas.addElement(programa.getNombre());
                    break;
                }
            }
        }

        jList3.setModel(modeloProgramas);
    }
    
