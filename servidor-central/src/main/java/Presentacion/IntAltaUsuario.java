    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        // TODO add your handling code here:
        //Aca va la llamada para guardar los datos ingresados, antes se debe comprobar que el nickname y el correo no existan previamente al guardado.
        String nickname = jTextField1.getText();
        String nombre = jTextField2.getText();
        String apellido = jTextField3.getText();
        String email = jTextField5.getText();
        
        String password = jTextField6.getText();
        
        if (nickname.trim().isEmpty()
        || nombre.trim().isEmpty()
        || apellido.trim().isEmpty()
        || email.trim().isEmpty()
        || password.trim().isEmpty()) {

    JOptionPane.showMessageDialog(
        this,
        "Debe completar todos los campos.",
        "Error",
        JOptionPane.ERROR_MESSAGE
    );
    return;
}

    LocalDate fechaNac;

try {
    fechaNac = LocalDate.parse(
        jFormattedTextField1.getText(),
        DateTimeFormatter.ofPattern("dd/MM/yyyy")
    );
} catch (Exception e) {
    JOptionPane.showMessageDialog(
        this,
        "La fecha de nacimiento no es válida.",
        "Error",
        JOptionPane.ERROR_MESSAGE
    );
    return;
}

LocalDate hoy = LocalDate.now();
LocalDate fechaMinima = hoy.minusYears(120);

if (fechaNac.isAfter(hoy)) {
    JOptionPane.showMessageDialog(
        this,
        "La fecha de nacimiento no puede ser mayor a la fecha actual.",
        "Error",
        JOptionPane.ERROR_MESSAGE
    );
    return;
}

if (fechaNac.isBefore(fechaMinima)) {
    JOptionPane.showMessageDialog(
        this,
        "Fecha de nacimiento invalida.",
        "Error",
        JOptionPane.ERROR_MESSAGE
    );
    return;
}

    Usuario usuario;
    String nombreInstituto = null;

    if (jCheckBox1.isSelected()) {

        nombreInstituto = seleCCInsti.getSelectedItem().toString();

        usuario = new Docente(
            nickname,
            email,
            nombre,
            apellido,
            fechaNac
        );

    } else {

        usuario = new Estudiante(
            nickname,
            email,
            nombre,
            apellido,
            fechaNac
        );
    }
    
    usuario.setPassword(password);

    boolean resultado;

    if (usuario instanceof Docente) {
        resultado = controladorUsuario.altaUsuario(usuario, nombreInstituto);
    } else {
        resultado = controladorUsuario.altaUsuario(usuario, null);
    }

    if (resultado) {

    // Si el usuario seleccionó una imagen, la guardamos
    if (imagenSeleccionada != null) {
        try {
            File carpetaImagenes = new File("imagenesUsuarios");

            // Crear la carpeta si no existe
            if (!carpetaImagenes.exists()) {
                carpetaImagenes.mkdirs();
            }

            // Obtener la extensión de la imagen
            String nombreArchivo = imagenSeleccionada.getName();
            String extension = nombreArchivo.substring(
                    nombreArchivo.lastIndexOf(".")
            ).toLowerCase();

            // La imagen se guarda usando el nickname
            File destino = new File(
                    carpetaImagenes,
                    nickname + extension
            );

            Files.copy(
                    imagenSeleccionada.toPath(),
                    destino.toPath(),
                    StandardCopyOption.REPLACE_EXISTING
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Usuario dado de alta correctamente."
            );

        } catch (IOException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "El usuario fue creado, pero no se pudo guardar la imagen."
            );

            e.printStackTrace();
        }

    } else {

        // No seleccionó imagen
        JOptionPane.showMessageDialog(
                this,
                "Usuario dado de alta correctamente."
        );
    }

} else {

    JOptionPane.showMessageDialog(
            this,
            "El nickname o correo electrónico ya está en uso."
    );
}

this.dispose();

    }//GEN-LAST:event_btnAceptarActionPerformed

