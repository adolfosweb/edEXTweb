    private void btnSeleccionarImagenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSeleccionarImagenActionPerformed
        // TODO add your handling code here:
        JFileChooser selector = new JFileChooser();

        FileNameExtensionFilter filtro =
        new FileNameExtensionFilter(
                "Imágenes JPG y PNG",
                "jpg", "jpeg", "png"
        );

        selector.setFileFilter(filtro);

        int resultado = selector.showOpenDialog(this);

        if (resultado == JFileChooser.APPROVE_OPTION) {

    imagenSeleccionada = selector.getSelectedFile();

    ImageIcon icono = new ImageIcon(imagenSeleccionada.getAbsolutePath());

    Image imagen = icono.getImage();

    Image imagenRedimensionada = imagen.getScaledInstance(
            lbImagen.getWidth(),
            lbImagen.getHeight(),
            Image.SCALE_SMOOTH
    );

    lbImagen.setIcon(new ImageIcon(imagenRedimensionada));
    lbImagen.setText("");
}
    }//GEN-LAST:event_btnSeleccionarImagenActionPerformed

