    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        // TODO add your handling code here:
            try {
            String nombreInstituto = (String) cbxInstituto.getSelectedItem();
            String nombreCurso = (String) cbxCursos.getSelectedItem();
            String nombreEdicion = txtNombreEdCurso.getText().trim();

            if (nombreInstituto == null || nombreCurso == null) {
                JOptionPane.showMessageDialog(this, "Debe seleccionar un Instituto y un Curso.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
                return;
            }

            if (nombreEdicion.isEmpty()) {
                JOptionPane.showMessageDialog(this, "El nombre de la edición no puede estar vacío.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
                return;
            }

            if (listModelDocentes.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Debe agregar al menos un docente a la lista.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 1. Obtener Fechas de los JSpinner
            java.util.Date dateInicio = (java.util.Date) spnFechaInicio.getValue();
            java.util.Date dateFin = (java.util.Date) spnFechaFin.getValue();

            LocalDate fechaInicio = dateInicio.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();
            LocalDate fechaFin = dateFin.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();
            LocalDate fechaPublicacion = LocalDate.now();

            if (fechaFin.isBefore(fechaInicio)) {
                JOptionPane.showMessageDialog(this, "La fecha de fin no puede ser anterior a la fecha de inicio.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 2. Cupo (Opcional)
            int cupo = 0;
            String cupoStr = txtCreditos.getText().trim(); 
            if (!cupoStr.isEmpty()) {
                try {
                    cupo = Integer.parseInt(cupoStr);
                    if (cupo < 0) {
                        JOptionPane.showMessageDialog(this, "El cupo no puede ser un número negativo.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
                        return;
                    }
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "El cupo debe ser un número entero válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }

            // 3. Buscar la entidad Curso
            Curso curso = controladorCurso.buscarCurso(nombreCurso);
            if (curso == null) {
                JOptionPane.showMessageDialog(this, "El curso seleccionado no existe.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 4. Verificar si ya existe una edición con ese nombre usando buscarEdicion
            EdicionCurso edicionExistente = controladorCurso.buscarEdicion(nombreEdicion);

            if (edicionExistente != null) {
                JOptionPane.showMessageDialog(
                    this, 
                    "Ya existe una edición registrada con el nombre '" + nombreEdicion + "'. Operación cancelada.", 
                    "Edición Existente", 
                    JOptionPane.WARNING_MESSAGE
                );
                return; // Se cancela el caso de uso sin fallar en compilación
            }

            // 5. Obtener la lista de objetos Docente agregados
            IControladorUsuario controladorUsuario = fabric.getControladorUsuario();
            java.util.List<Docente> listaDocentes = new java.util.ArrayList<>();

            for (int i = 0; i < listModelDocentes.getSize(); i++) {
                String nickDocente = listModelDocentes.getElementAt(i);
                Usuario u = controladorUsuario.buscarUsuario(nickDocente);
                if (u instanceof Docente) {
                    listaDocentes.add((Docente) u);
                }
            }

            // 6. Alta de la nueva Edición de Curso
            EdicionCurso nuevaEdicion = new EdicionCurso(
                nombreEdicion, 
                fechaInicio, 
                fechaFin, 
                cupo, 
                fechaPublicacion, 
                curso, 
                null
            );

            // Vincular los docentes agregados desde el ListModel
            for (Docente d : listaDocentes) {
                nuevaEdicion.agregarDocente(d);
            }

            boolean exito = controladorCurso.altaEdicion(nuevaEdicion);

            if (exito) {
                JOptionPane.showMessageDialog(this, "La edición '" + nombreEdicion + "' se ha registrado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Ocurrió un error al intentar registrar la edición.", "Error de Persistencia", JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
            
    this.dispose();

    }//GEN-LAST:event_btnAceptarActionPerformed

