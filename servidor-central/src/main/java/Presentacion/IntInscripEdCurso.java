    private void cargarEstudiantes() {
        cbxEstudiantes.removeAllItems();
        if (controladorUsuario != null) {
            Map<String, Usuario> usuarios = controladorUsuario.listarUsuarios();
            if (usuarios != null) {
                for (Usuario u : usuarios.values()) {
                    // Si tienes una clase hija Estudiante o filtras por tipo de usuario:
                    if (u instanceof Estudiante) { 
                        cbxEstudiantes.addItem(u.getNickname()); // O u.getCorreo() según la clave primaria usada
                    }
                }
            }
        }
    }

