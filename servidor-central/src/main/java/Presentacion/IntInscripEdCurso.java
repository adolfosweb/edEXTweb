    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        // TODO add your handling code here:
            try {
            String nickEstudiante = (String) cbxEstudiantes.getSelectedItem();
            String nombreEdicion = (String) cbxEdCursos.getSelectedItem();
            String nombreCurso = (String) cbxCursos.getSelectedItem();
            String nombreInst = (String) cbxInstituto.getSelectedItem();

            // 1. Validar selecciones de los ComboBoxes
            if (nombreInst == null || nombreCurso == null || nombreEdicion == null || nickEstudiante == null) {
                JOptionPane.showMessageDialog(this, "Debe seleccionar un Instituto, un Curso, una Edición y un Estudiante.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 2. Buscar las entidades correspondientes
            EdicionCurso edicion = controladorCurso.buscarEdicion(nombreEdicion);
            Usuario u = controladorUsuario.buscarUsuario(nickEstudiante);

            if (edicion == null || !(u instanceof Estudiante)) {
                JOptionPane.showMessageDialog(this, "La edición o el estudiante seleccionado no existen en el sistema.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            Estudiante estudiante = (Estudiante) u;

            // 3. Validar que la edición no tenga una configuración de cupo negativa
            if (edicion.getCupo() < 0) {
                JOptionPane.showMessageDialog(this, "La edición seleccionada no tiene cupos disponibles.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 4. Validar disponibilidad de cupos (si cupo > 0 representa un límite establecido)
            int cupoMaximo = edicion.getCupo();
            int inscriptosActuales = (edicion.getInscriptos() != null) ? edicion.getInscriptos().size() : 0;

            if (cupoMaximo > 0 && inscriptosActuales >= cupoMaximo) {
                JOptionPane.showMessageDialog(
                    this, 
                    "No hay cupos disponibles para la edición '" + nombreEdicion + "' (" + inscriptosActuales + "/" + cupoMaximo + ").", 
                    "Cupo Agotado", 
                    JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            // 5. Verificar si el estudiante ya se encuentra inscripto a la edición
            Logica.InscripcionCurso inscripcionExistente = controladorCurso.buscarInscripcion(nickEstudiante, nombreEdicion);

            if (inscripcionExistente != null) {
                JOptionPane.showMessageDialog(
                    this, 
                    "El estudiante '" + nickEstudiante + "' ya está inscripto a la edición '" + nombreEdicion + "'.", 
                    "Inscripción Existente", 
                    JOptionPane.WARNING_MESSAGE
                );
                return; // Se cancela el flujo sin cerrar intencionalmente la ventana
            }

            // 6. Obtener la fecha seleccionada en el JSpinner
            java.util.Date dateInscripcion = (java.util.Date) spnFechaInscrip.getValue();
            LocalDate fechaInscripcion = dateInscripcion.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();

            // 7. Instanciar y registrar la nueva inscripción
            Logica.InscripcionCurso nuevaInscripcion = new Logica.InscripcionCurso(estudiante, fechaInscripcion, edicion);

            boolean exito = controladorCurso.inscribirEstudiante(nuevaInscripcion);

            if (exito) {
                JOptionPane.showMessageDialog(this, "Estudiante registrado con éxito en la edición.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                this.dispose(); // Cierra el formulario únicamente tras la persistencia exitosa
            } else {
                JOptionPane.showMessageDialog(this, "Ocurrió un error al procesar la inscripción en la base de datos.", "Error de Registro", JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
        this.dispose();
    }//GEN-LAST:event_btnAceptarActionPerformed

    private void cbxInstitutoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbxInstitutoActionPerformed
        // TODO add your handling code here:
        cbxCursos.removeAllItems();

        String nombreInst = (String) cbxInstituto.getSelectedItem();
        if (nombreInst != null && controladorCurso != null) {
            // Obtenemos los cursos registrados
            Map<String, Curso> mapaCursos = controladorCurso.listarCursos();

            if (mapaCursos != null) {
                for (Curso c : mapaCursos.values()) {
                    // Filtramos únicamente los cursos que pertenecen al instituto seleccionado
                    if (c.getInstituto() != null && nombreInst.equals(c.getInstituto().getNombre())) {
                        cbxCursos.addItem(c.getNombre());
                    }
                }
            }
        }
    }//GEN-LAST:event_cbxInstitutoActionPerformed

    private void cbxCursosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbxCursosActionPerformed
        // TODO add your handling code here:
        cbxEdCursos.removeAllItems();

        String nombreCurso = (String) cbxCursos.getSelectedItem();
        if (nombreCurso != null && !nombreCurso.isEmpty()) {
            Map<String, EdicionCurso> mapaEdiciones = controladorCurso.listarEdiciones();
            if (mapaEdiciones != null) {
                for (EdicionCurso ed : mapaEdiciones.values()) {
                    if (ed.getCurso() != null && nombreCurso.equals(ed.getCurso().getNombre())) {
                        cbxEdCursos.addItem(ed.getNombre());
                    }
                }
            }
        }

    }//GEN-LAST:event_cbxCursosActionPerformed

