    private void acomodarVentanasMinimizadas() {
    int x = 10;
    int y = 10;
    int separacion = 10;

    for (JInternalFrame frame : jDesktopPane1.getAllFrames()) {
        if (frame.isIcon()) {
            frame.getDesktopIcon().setLocation(x, y);

            x += frame.getDesktopIcon().getWidth() + separacion;

            // Si no entra más a la derecha, baja a la siguiente fila
            if (x + 100 > jDesktopPane1.getWidth()) {
                x = 10;
                y += frame.getDesktopIcon().getHeight() + separacion;
            }
        }
    }
}
    
    private void abrirVentana(JInternalFrame ventana) {

    ventana.addInternalFrameListener(new javax.swing.event.InternalFrameAdapter() {
        @Override
        public void internalFrameIconified(javax.swing.event.InternalFrameEvent e) {
            acomodarVentanasMinimizadas();
        }

        @Override
        public void internalFrameDeiconified(javax.swing.event.InternalFrameEvent e) {
            acomodarVentanasMinimizadas();
        }
    });

    jDesktopPane1.add(ventana);
    ventana.setVisible(true);

    try {
        ventana.setSelected(true);
    } catch (java.beans.PropertyVetoException e) {
    }
}
