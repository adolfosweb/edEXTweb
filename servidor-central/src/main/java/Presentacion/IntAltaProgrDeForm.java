    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String nombre = jTextField1.getText().trim();
        String descripcion = jTextArea2.getText().trim();
        String fInicio = jFormattedTextField4.getText().trim();
        String fFin = jFormattedTextField3.getText().trim();

        // Validar campos vacíos
        if (nombre.isEmpty() || descripcion.isEmpty() || fInicio.isEmpty() || fFin.isEmpty() ||
                fInicio.equals("DD/MM/YYYY") || fFin.equals("DD/MM/YYYY")) {

            JOptionPane.showMessageDialog(this,"Datos inválidos");
            return;
        }

        DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy");

        try {
            LocalDate fechaInicio = LocalDate.parse(fInicio, formato);
            LocalDate fechaFin = LocalDate.parse(fFin, formato);

            // La fecha de alta se genera automáticamente
            LocalDate fechaAlta = LocalDate.now();
            jFormattedTextField1.setText(fechaAlta.format(formato));

            ProgramaFormacion programa = new ProgramaFormacion(nombre,descripcion,fechaInicio,fechaFin);

            boolean res = controlador.altaPrograma(programa);

            if (res) {
                JOptionPane.showMessageDialog(this,"Programa creado correctamente");
            } else {
                JOptionPane.showMessageDialog(this,"Ya existe un programa con ese nombre");
            }
        } catch (java.time.format.DateTimeParseException e) {
            JOptionPane.showMessageDialog(this,"Las fechas deben tener el formato DD/MM/YYYY");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

