    private void btnAgregarPreviaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarPreviaActionPerformed
        // TODO add your handling code here:
        String cursoSeleccionado = (String) cbxPrevias.getSelectedItem();
        String cursoActual = txtNombreCurso.getText().trim();

        if (cursoSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un curso de la lista.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Validar que un curso no sea previa de sí mismo
        if (!cursoActual.isEmpty() && cursoSeleccionado.equalsIgnoreCase(cursoActual)) {
            JOptionPane.showMessageDialog(this, "Un curso no puede ser previa de sí mismo.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Evitar duplicados en la lista visual
        if (listModelPrevias.contains(cursoSeleccionado)) {
            JOptionPane.showMessageDialog(this, "El curso '" + cursoSeleccionado + "' ya fue agregado a la lista de previas.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Agregar elemento al modelo de la JList
        listModelPrevias.addElement(cursoSeleccionado);
    }//GEN-LAST:event_btnAgregarPreviaActionPerformed


