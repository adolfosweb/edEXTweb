    private void cargarCursosEnPrevias() {
        cbxPrevias.removeAllItems();
        if (controladorCurso != null) {
            java.util.Map<String, Curso> cursosMap = controladorCurso.listarCursos();
            if (cursosMap != null) {
                for (Curso c : cursosMap.values()) {
                    cbxPrevias.addItem(c.getNombre());
                }
            }
        }
    }

