    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        // TODO add your handling code here:
        //Aca va la llamada para guardar los datos ingresados, antes se debe comprobar que el nickname y el correo no existan previamente al guardado.
        try {
        String nombre = txtNombreCurso.getText().trim();
        String descripcion = txtDescCurso.getText().trim();
        String duracion = txtDuracion.getText().trim();
        String horasStr = txtCantHoras.getText().trim();
        String creditosStr = txtCreditos.getText().trim();
        String url = txtUrl.getText().trim();
        String nombreInstituto = (String) cbxInstituto.getSelectedItem();

        if (nombre.isEmpty() || descripcion.isEmpty() || duracion.isEmpty() || nombreInstituto == null) {
            JOptionPane.showMessageDialog(this, "Debe completar todos los campos obligatorios.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int cantHoras = Integer.parseInt(horasStr);
        int cantCreditos = Integer.parseInt(creditosStr);
        Instituto inst = controladorInstituto.buscarInstituto(nombreInstituto);

        // 1. Verificar si el curso ya existe
        Curso cursoExistente = controladorCurso.buscarCurso(nombre);

        if (cursoExistente != null) {
            JOptionPane.showMessageDialog(
                this, 
                "Ya existe un curso con el nombre '" + nombre + "'. Si desea modificarlo, realice los cambios necesarios en este formulario y vuelva a presionar Aceptar.", 
                "Curso Existente", 
                JOptionPane.WARNING_MESSAGE
            );
            return; // Se detiene la ejecución dejando la ventana abierta
        }

        // 2. Obtener fecha del JSpinner
        Date fechaRegistro = (Date) spnFechaAlta.getValue();

        // 3. Crear e instanciar el nuevo curso
        Curso nuevoCurso = new Curso(nombre, descripcion, duracion, cantHoras, cantCreditos, fechaRegistro, url);
        nuevoCurso.setInstituto(inst);

        // 4. Recorrer el JList para agregar las previas
        for (int i = 0; i < listModelPrevias.getSize(); i++) {
            String nombrePrevia = listModelPrevias.getElementAt(i);
            Curso previa = controladorCurso.buscarCurso(nombrePrevia);
            if (previa != null) {
                nuevoCurso.agregarPrevia(previa);
            }
        }

        // 5. Persistir en la Base de Datos
        boolean exito = controladorCurso.altaCurso(nuevoCurso);

        if (exito) {
            JOptionPane.showMessageDialog(this, "Curso registrado con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            this.dispose(); // Cierra el formulario solo tras un guardado exitoso
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar el curso.", "Error de Persistencia", JOptionPane.ERROR_MESSAGE);
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "La cantidad de horas y créditos deben ser números enteros válidos.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Ocurrió un error al procesar el curso: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }


    this.dispose();

    
    }//GEN-LAST:event_btnAceptarActionPerformed

