    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:  
        if(jComboBox1.getSelectedItem() == null || jComboBox2.getSelectedItem() == null){
            JOptionPane.showMessageDialog(this, "Datos invalidos");
        }else{
            String nomPrograma = jComboBox1.getSelectedItem().toString();
            String nomCurso = jComboBox2.getSelectedItem().toString();
            
            boolean res = controladorP.agregarCurso(nomPrograma, nomCurso);

            if(res){
                JOptionPane.showMessageDialog(this,"Curso agregado correctamente");
            } else {
                JOptionPane.showMessageDialog(this,"No se pudo agregar el curso");
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

