    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
       String nombre = txtNombreCurso.getText().trim();

    if (nombre.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Debe ingresar el nombre de la categoría."
        );
        return;
    }

    Categoria existente = controladorCategoria.buscarCategoria(nombre);

    if (existente != null) {

        int opcion = JOptionPane.showConfirmDialog(
                this,
                "Ya existe una categoría con ese nombre.\n"
                + "¿Desea ingresar otro nombre?",
                "Categoría existente",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (opcion == JOptionPane.YES_OPTION) {
            txtNombreCurso.requestFocus();
            txtNombreCurso.selectAll();
        } else {
            this.dispose();
        }

        return;
    }

    Categoria categoria = new Categoria(nombre);

    boolean creada = controladorCategoria.altaCategoria(categoria);

    if (creada) {
        JOptionPane.showMessageDialog(
                this,
                "Categoría registrada correctamente."
        );

        txtNombreCurso.setText("");
        this.dispose();

    } else {
        JOptionPane.showMessageDialog(
                this,
                "No se pudo registrar la categoría.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_jButton1ActionPerformed

