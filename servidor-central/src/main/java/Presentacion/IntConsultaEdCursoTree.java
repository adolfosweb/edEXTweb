    private java.util.Date convertirADate(Object fecha) {
        if (fecha instanceof java.util.Date) {
            return (java.util.Date) fecha;
        } else if (fecha instanceof java.time.LocalDate) {
            return java.util.Date.from(((java.time.LocalDate) fecha).atStartOfDay(java.time.ZoneId.systemDefault()).toInstant());
        }
        return new java.util.Date();
    }



