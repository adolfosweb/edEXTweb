    private void cargarArbolCursos() {
    javax.swing.tree.DefaultMutableTreeNode raiz = new javax.swing.tree.DefaultMutableTreeNode("Institutos");

    Fabric fabric = Fabric.getInstancia();
    IControladorInstituto controladorInstituto = fabric.getControladorInstituto();
    IControladorCurso controladorCurso = fabric.getControladorCurso();

    if (controladorInstituto != null) {
        Map<String, Instituto> institutos = controladorInstituto.listarInstitutos();
        Map<String, Curso> cursos = controladorCurso.listarCursos();
        Map<String, EdicionCurso> ediciones = controladorCurso.listarEdiciones();

        if (institutos != null) {
            for (Instituto inst : institutos.values()) {
                javax.swing.tree.DefaultMutableTreeNode nodoInst = new javax.swing.tree.DefaultMutableTreeNode(inst.getNombre());

                if (cursos != null) {
                    for (Curso curso : cursos.values()) {
                        if (curso.getInstituto() != null && inst.getNombre().equals(curso.getInstituto().getNombre())) {
                            javax.swing.tree.DefaultMutableTreeNode nodoCurso = new javax.swing.tree.DefaultMutableTreeNode(curso.getNombre());

                            if (ediciones != null) {
                                for (EdicionCurso ed : ediciones.values()) {
                                    if (ed.getCurso() != null && curso.getNombre().equals(ed.getCurso().getNombre())) {
                                        javax.swing.tree.DefaultMutableTreeNode nodoEdicion = new javax.swing.tree.DefaultMutableTreeNode(ed.getNombre());
                                        nodoCurso.add(nodoEdicion);
                                    }
                                }
                            }
                            nodoInst.add(nodoCurso);
                        }
                    }
                }
                raiz.add(nodoInst);
            }
        }
    }
        treeCursos.setModel(new javax.swing.tree.DefaultTreeModel(raiz));
    }
    
