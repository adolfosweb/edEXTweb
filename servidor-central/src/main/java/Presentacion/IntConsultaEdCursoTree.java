    private void treeCursosValueChanged(javax.swing.event.TreeSelectionEvent evt) {//GEN-FIRST:event_treeCursosValueChanged
        // TODO add your handling code here:
        javax.swing.tree.DefaultMutableTreeNode nodoSeleccionado = 
        (javax.swing.tree.DefaultMutableTreeNode) treeCursos.getLastSelectedPathComponent();

        if (nodoSeleccionado == null) {
            limpiarCampos();
            return;
        }

        // Verificar si se seleccionó una Edición (nodo del nivel 3: Institutos -> Curso -> Edición)
        if (nodoSeleccionado.isLeaf() && nodoSeleccionado.getLevel() == 3) {
            String nombreEdicion = nodoSeleccionado.getUserObject().toString();

            IControladorCurso controladorCurso = Fabric.getInstancia().getControladorCurso();
            EdicionCurso edicion = controladorCurso.buscarEdicion(nombreEdicion);

            if (edicion != null) {
                tbxNombre.setText(String.valueOf(edicion.getNombre()));
                tbxCupo.setText(String.valueOf(edicion.getCupo()));

                if (edicion.getFechaInicio() != null) {
                    spnFechaInicio.setValue(convertirADate(edicion.getFechaInicio()));
                }
                if (edicion.getFechaFin() != null) {
                    spnFechaFin.setValue(convertirADate(edicion.getFechaFin()));
                }
            }
        } else {
            limpiarCampos();
        }
    }//GEN-LAST:event_treeCursosValueChanged


