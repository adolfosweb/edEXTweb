    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        if (jComboBox2.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this, "No hay ningún curso seleccionado");
        return;
        }

        String nombreCurso = jComboBox2.getSelectedItem().toString();

        ProgramaFormacion programa = controlador.buscarPrograma(
                jComboBox1.getSelectedItem().toString()
        );

        Curso curso = null;

        for (Curso c : programa.getCursos()) {
            if (c.getNombre().equals(nombreCurso)) {
                curso = c;
                break;
            }
        }

        if (curso == null) {
            JOptionPane.showMessageDialog(this, "No se encontró el curso");
            return;
        }

        IntConsultaCurso ventana = new IntConsultaCurso(curso);

        JDesktopPane desktop = this.getDesktopPane();
        desktop.add(ventana);
        ventana.setVisible(true);
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        if(jComboBox1.getSelectedItem() == null){
            JOptionPane.showMessageDialog(this, "No existen Programas");
        }else{
            cargarPrograma(jComboBox1.getSelectedItem().toString());
        }
    }//GEN-LAST:event_jButton4ActionPerformed

    private void cargarPrograma(String nomPrograma){
        ProgramaFormacion programa = controlador.buscarPrograma(nomPrograma);
            
        jTextField1.setText(programa.getNombre());
        jTextArea1.setText(programa.getDescripcion());
        jFormattedTextField1.setText(programa.getFechaInicio().toString());
        jFormattedTextField2.setText(programa.getFechaFin().toString());
        jFormattedTextField3.setText(programa.getFechaAlta().toString());
        
        jComboBox2.removeAllItems();
        for(Curso c : programa.getCursos()){
            jComboBox2.addItem(c.getNombre());
        }
    }

